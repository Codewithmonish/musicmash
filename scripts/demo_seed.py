"""
DEV ONLY: create a demo analysis through the real Spring API, end to end.

1. Generates a 12-note melody (a C-major scale up and back down, 0.5 s per note at 120 BPM)
   with exactly one note, the E4, played 40 cents sharp.
2. Registers (or logs in) a demo user, uploads the WAV, creates a performance and asks
   Spring to analyse it, exactly like the frontend would.
3. Waits for the AI service to finish and prints the AI Analysis page URL.

The analysis id is saved to logs/demo_seed.json for scripts/e2e_screenshot.py.

Usage (services running, from the repo root):
    music-mash-ai\\.venv\\Scripts\\python scripts\\demo_seed.py
Env: MUSICMASH_API (default http://localhost:8081/api), MUSICMASH_DEMO_EMAIL,
     MUSICMASH_DEMO_PASSWORD (a throwaway local dev password, not a secret).
"""
import io
import json
import os
import sys
import time
from pathlib import Path

import httpx
import numpy as np
import soundfile as sf

API = os.environ.get("MUSICMASH_API", "http://localhost:8081/api")
FRONTEND = os.environ.get("MUSICMASH_FRONTEND", "http://localhost:5173")
EMAIL = os.environ.get("MUSICMASH_DEMO_EMAIL", "demo@musicmash.local")
PASSWORD = os.environ.get("MUSICMASH_DEMO_PASSWORD", "demo-pass-123")
USERNAME = "demo_player"

SR = 22050
NOTE_S = 0.5            # 120 BPM, one note per beat
GAP_S = 0.05            # short silence between notes so every note has a clear onset
SHARP_NOTE = "E4"
SHARP_CENTS = 40.0
MELODY = ["C4", "D4", "E4", "F4", "G4", "A4", "B4", "C5", "B4", "A4", "G4", "F4"]
SEED_FILE = Path(__file__).resolve().parents[1] / "logs" / "demo_seed.json"


def note_hz(name: str) -> float:
    """Equal-tempered frequency (A4 = 440 Hz) of a note name like 'C#4'."""
    names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    midi = names.index(name[:-1]) + 12 * (int(name[-1]) + 1)
    return 440.0 * 2 ** ((midi - 69) / 12)


def make_melody() -> bytes:
    """The demo melody as WAV bytes. Only the first E4 is detuned by SHARP_CENTS."""
    tone_n, gap_n = int(SR * (NOTE_S - GAP_S)), int(SR * GAP_S)
    attack_n, release_n = int(SR * 0.01), int(SR * 0.04)
    envelope = np.ones(tone_n)
    envelope[:attack_n] = np.linspace(0, 1, attack_n)
    # Smooth 40 ms release: a 10 ms linear cut-off is effectively a click, which onset
    # detection rightly reports as a second "onset" at the end of every note.
    envelope[-release_n:] = 0.5 * (1 + np.cos(np.linspace(0, np.pi, release_n)))
    t = np.arange(tone_n) / SR
    parts, sharpened = [], False
    for name in MELODY:
        freq = note_hz(name)
        if name == SHARP_NOTE and not sharpened:
            freq *= 2 ** (SHARP_CENTS / 1200)
            sharpened = True
        parts += [0.5 * envelope * np.sin(2 * np.pi * freq * t), np.zeros(gap_n)]
    buffer = io.BytesIO()
    sf.write(buffer, np.concatenate(parts).astype(np.float32), SR, format="WAV")
    return buffer.getvalue()


def check(response: httpx.Response, what: str) -> dict:
    if response.status_code >= 400:
        sys.exit(f"{what} failed: HTTP {response.status_code} {response.text[:300]}")
    return response.json()


def get_token(client: httpx.Client) -> str:
    register = client.post("/auth/register", json={
        "username": USERNAME, "email": EMAIL, "password": PASSWORD, "role": "USER"})
    if register.status_code < 400:
        print(f"Registered demo user {EMAIL}")
        return register.json()["token"]
    if register.status_code != 409:
        check(register, "Register")
    print(f"Demo user {EMAIL} already exists, logging in")
    return check(client.post("/auth/login", json={"email": EMAIL, "password": PASSWORD}), "Login")["token"]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    with httpx.Client(base_url=API, timeout=30) as client:
        client.headers["Authorization"] = f"Bearer {get_token(client)}"

        upload = check(client.post("/upload/audio", files={
            "file": ("demo-melody.wav", make_melody(), "audio/wav")}), "Upload")
        print(f"Uploaded melody -> {upload['url']}")

        performance = check(client.post("/performances", json={
            "title": "Demo: C-major scale with a sharp E4",
            "description": f"Generated by scripts/demo_seed.py; {SHARP_NOTE} is {SHARP_CENTS:+.0f} cents.",
            "category": "CLASSICAL", "instrument": "VIOLIN", "difficulty": "BEGINNER",
            "audioUrl": upload["url"]}), "Create performance")
        print(f"Created performance {performance['id']}")

        analysis = check(client.post("/ai/analyze", json={
            "performanceId": performance["id"], "audioUrl": upload["url"],
            "instrument": "VIOLIN", "category": "CLASSICAL"}), "Submit analysis")
        analysis_id = analysis["id"]
        print(f"Submitted analysis {analysis_id}, waiting for the AI service...")

        deadline = time.monotonic() + 300
        while True:
            status = check(client.get(f"/ai/status/{analysis_id}"), "Status")
            if status["status"] in ("COMPLETED", "FAILED"):
                break
            if time.monotonic() > deadline:
                sys.exit(f"Analysis {analysis_id} still {status['status']} after 300 s")
            time.sleep(2)
        if status["status"] == "FAILED":
            sys.exit(f"Analysis {analysis_id} FAILED: {status['error_message']}")

        result = check(client.get(f"/ai/result/{analysis_id}"), "Result")
        features, skill = result["audio_features"], result["skill_prediction"]
        sharp = [n for n in features["notes"] if n["note_name"] == SHARP_NOTE]
        print(f"Analysis {analysis_id} COMPLETED")
        print(f"  notes: {' '.join(n['note_name'] for n in features['notes'])}")
        measured = ", ".join("%+.1f cents" % n["mean_cents"] for n in sharp)
        print(f"  {SHARP_NOTE} measured: {measured}")
        print(f"  intonation {skill['intonation_score']}  rhythm {skill['rhythm_score']}  "
              f"overall {skill['overall_score']}  level {skill['predicted_level']}")

    SEED_FILE.parent.mkdir(exist_ok=True)
    SEED_FILE.write_text(json.dumps({"analysis_id": analysis_id, "email": EMAIL}, indent=2))
    print(f"\nOpen: {FRONTEND}/ai-analysis/{analysis_id}  (log in as {EMAIL})")


if __name__ == "__main__":
    main()
